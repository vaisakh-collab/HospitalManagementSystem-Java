public class Person{
    private String name;
    private int age;
    private String phone;
    private String address;
    private String email;

    public Person(String name, int age, String phone, String address, String email){
        this.name = name;
        this.age = age;
        this.phone = phone;
        this.address = address;
        this.email = email;
    }
}